#!/usr/bin/env python3
"""Generates the data tables of the npu_top directed programs (plan Phase 2 Task 14).

Writes data_k64.inc, data_k1024.inc and data_war.inc next to this script. The inputs are fixed
pseudo-random int8 matrices (explicit seeds); the expected accumulators are computed here, in plain
Python integers from the definition in spec 6.2/6.3, acc[i][j] = sum_k W[i][k] * X[j][k], and have
no connection to the DUT, to npu_ref.c or to the golden model. The .inc files are committed, so the
build needs no Python. Run: python3 gen_data.py
"""
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
M32 = 0xFFFFFFFF


def rand_mat(rng, k):
    """4 x k int8 matrix; the extremes -128 and 127 are forced in so that sign handling is hit."""
    m = [[rng.randint(-128, 127) for _ in range(k)] for _ in range(4)]
    m[0][0], m[1][1], m[2][2], m[3][3] = -128, 127, -128, 127
    m[0][k - 1], m[3][k - 2] = -128, -128
    return m


def quad_words(m, k):
    """Memory image of a 4 x k matrix (spec 6.2): quad s, word r = bytes m[r][4s..4s+3], lane 0 = LSB."""
    words = []
    for s in range(k // 4):
        for r in range(4):
            w = 0
            for t in range(4):
                w |= (m[r][4 * s + t] & 0xFF) << (8 * t)
            words.append(w)
    return words


def expected(w, x, k):
    """acc[4*i + j] as 32-bit patterns."""
    return [sum(w[i][t] * x[j][t] for t in range(k)) & M32 for i in range(4) for j in range(4)]


def scale(vals, n):
    return [(v * n) & M32 for v in vals]


def emit(f, label, words, per_line=4, align=None):
    if align:
        f.write("    .balign %d\n" % align)
    f.write("%s:\n" % label)
    for i in range(0, len(words), per_line):
        f.write("    .word " + ", ".join("0x%08X" % v for v in words[i:i + per_line]) + "\n")


def header(f, text):
    f.write("# Generated by gen_data.py - do not edit. %s\n" % text)
    f.write("# Expected values are plain-Python dot products (spec 6.2), independent of the DUT.\n")


def check_signed_nonzero(vals):
    # The self-checks of the data: a table of zeros or of equal values would prove little.
    assert all(v != 0 for v in vals), "zero accumulator in an expected table"
    assert len(set(vals)) >= 12, "expected table has too many equal entries"


def gen_k64():
    rng = random.Random(14064)
    k = 64
    w, x = rand_mat(rng, k), rand_mat(rng, k)
    e1 = expected(w, x, k)
    check_signed_nonzero(e1)
    assert any(v >= 1 << 31 for v in e1) and any(v < 1 << 31 for v in e1), "want both signs"
    with open(os.path.join(HERE, "data_k64.inc"), "w", newline="\n") as f:
        header(f, "K = 64 (16 quads), seed 14064.")
        emit(f, "w64", quad_words(w, k), align=16)
        emit(f, "i64", quad_words(x, k), align=16)
        emit(f, "e1", e1)        # clr = 1 once
        emit(f, "e2", scale(e1, 2))
        emit(f, "e3", scale(e1, 3))
        emit(f, "e11", scale(e1, 11))
        emit(f, "e20", scale(e1, 20))


def gen_k1024():
    rng = random.Random(141024)
    k = 1024
    w, x = rand_mat(rng, k), rand_mat(rng, k)
    e = expected(w, x, k)
    check_signed_nonzero(e)
    with open(os.path.join(HERE, "data_k1024.inc"), "w", newline="\n") as f:
        header(f, "K = 1024 (256 quads = KMAX), seed 141024.")
        emit(f, "w1024", quad_words(w, k), align=16)
        emit(f, "i1024", quad_words(x, k), align=16)
        emit(f, "e1024", e)


def gen_war():
    rng = random.Random(14016)
    k = 16
    wa, xa = rand_mat(rng, k), rand_mat(rng, k)
    wb, xb = rand_mat(rng, k), rand_mat(rng, k)
    ea, eb = expected(wa, xa, k), expected(wb, xb, k)
    check_signed_nonzero(ea)
    check_signed_nonzero(eb)
    assert all(a != b for a, b in zip(ea, eb)), "A and B must differ at every index"
    with open(os.path.join(HERE, "data_war.inc"), "w", newline="\n") as f:
        header(f, "K = 16 (4 quads), two data sets A and B, seed 14016.")
        # buf_w and buf_i are adjacent: one 32-word copy replaces both (initially set A)
        emit(f, "buf_w", quad_words(wa, k), align=16)
        emit(f, "buf_i", quad_words(xa, k), align=16)
        emit(f, "src_a", quad_words(wa, k) + quad_words(xa, k), align=16)
        emit(f, "src_b", quad_words(wb, k) + quad_words(xb, k), align=16)
        emit(f, "ea", ea)
        emit(f, "eb", eb)


if __name__ == "__main__":
    gen_k64()
    gen_k1024()
    gen_war()
    print("gen_data.py: wrote data_k64.inc data_k1024.inc data_war.inc")
